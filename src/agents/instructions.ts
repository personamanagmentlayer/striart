/**
 * Écrit le fichier de réglages de session d'un profil (`settingsFile`) et
 * rend les arguments qui le passent à l'outil (`flag chemin`), ou [] sans
 * réglages. `claudeMdExcludes` y ajoute les CLAUDE.md du worktree principal.
 */
export async function writeSessionSettings({
  root,
  agent,
  taskId,
  cwd,
  profile,
}: {
  root: string;
  agent: string;
  taskId: string;
  cwd: string;
  profile: AgentProfile;
}): Promise<string[]> {
  const spec = profile.settingsFile;
  if (!spec) return [];
  const json: Record<string, unknown> = { ...spec.json };
  if (spec.claudeMdExcludes && path.resolve(cwd) !== path.resolve(root)) {
    const given = Array.isArray(json.claudeMdExcludes) ? (json.claudeMdExcludes as unknown[]) : [];
    json.claudeMdExcludes = [...given, ...parentInstructionExcludes(root, cwd)];
  }
  const file = sessionSettingsPath(root, agent, taskId);
  await mkdirPrivate(path.dirname(file));
  await writeFile(file, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
  return [spec.flag, file];
}

/** Enveloppe : consignes puis tâche, séparées sans ambiguïté. */
export function wrapPrompt(instructions: string, prompt: string): string {
  return `${instructions.trimEnd()}\n\n---\n\n# Task\n\n${prompt}`;
}

