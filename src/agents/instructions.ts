/**
 * Prépare le canal de consignes d'un profil ARGV : écrit le fichier de
 * consignes hors du clone si besoin, et dit comment remplir l'argv. La
 * substitution elle-même est faite en UNE passe par buildAgentArgv
 * (session.js) — jamais de re-substitution d'un texte déjà inséré.
 */
export async function planArgvInstructions({
  root,
  agent,
  taskId,
  instructions,
  profile,
  prompt,
}: {
  root: string;
  agent: string;
  taskId: string;
  instructions: string | null;
  profile: AgentProfile;
  prompt: string;
}): Promise<ArgvInstructionsPlan> {
  const channel = resolveInstructionsChannel(profile);
  const args = profile.args ?? [];
  const toml = profile.instructions?.encoding === 'toml-string';
  // Encodage de l'emplacement texte : une chaîne TOML (`-c clé="…"` de Codex)
  // est produite par JSON.stringify — ses échappements (\n, \", \\, \uXXXX)
  // sont tous des échappements valides d'une chaîne TOML de base.
  const encode = (text: string) => (toml ? JSON.stringify(text) : text);
  const none: ArgvInstructionsPlan = {
    channel: 'none',
    prompt,
    slots: { instructions: toml ? '""' : '', instructionsFile: '' },
    appendArgs: [],
    instructionsFile: null,
  };
  if (channel === 'acp-prompt') {
    throw new StriartError(
      'Profile instructions channel "acp-prompt" requires an ACP profile (acp: true).',
      {
        code: 'PROFILE_INVALID',
        hint: 'striart profiles',
        details: { reason: 'INSTRUCTIONS_CHANNEL_TRANSPORT', field: 'instructions.channel' },
      },
    );
  }
  if (instructions === null || channel === 'none') return none;

  if (channel === 'system-prompt-file') {
    const hasFileSlot = args.some((a) => a.includes(INSTRUCTIONS_FILE_PLACEHOLDER));
    const flag = profile.instructions?.flag ?? null;
    if (!hasFileSlot && !flag) {
      throw new StriartError(
        'Profile instructions channel "system-prompt-file" needs instructions.flag or a {{striartInstructionsFile}} argument.',
        {
          code: 'PROFILE_INVALID',
          hint: 'striart profiles',
          details: { reason: 'INSTRUCTIONS_FLAG_MISSING', field: 'instructions.flag' },
        },
      );
    }
    const file = sessionInstructionsPath(root, agent, taskId);
    await mkdirPrivate(path.dirname(file));
    await writeFile(file, instructions, 'utf8');
    return {
      channel,
      prompt,
      slots: { instructions: '', instructionsFile: file },
      appendArgs: hasFileSlot ? [] : [flag as string, file],
      instructionsFile: file,
    };
  }

  // Canal 'prompt' : emplacement dédié s'il existe, sinon enveloppe du prompt.
  if (args.some((a) => a.includes(INSTRUCTIONS_PLACEHOLDER))) {
    return {
      ...none,
      channel,
      slots: { instructions: encode(instructions), instructionsFile: '' },
    };
  }
  return { ...none, channel, prompt: wrapPrompt(instructions, prompt) };
}

