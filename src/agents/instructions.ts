/**
 * Consignes Striart remises aux agents de coding (lot I5).
 *
 * Un agent lancé dans un clone ne sait rien de Striart : qu'il est isolé,
 * que seul le travail COMMITÉ est intégré, que le Test Gate décide, qu'il ne
 * doit jamais pousser ni toucher aux fichiers de configuration d'agent. Ce
 * module produit ce texte (gabarit complet par défaut, surchargeable par la
 * config et par profil) et le remet par le CANAL adapté :
 *
 *  - ACP : bloc en tête du prompt (appelé par acp.ts) ;
 *  - argv : fichier de consignes système hors du clone (`system-prompt-file`,
 *    ex. `--append-system-prompt-file`), sinon enveloppe du prompt ;
 *  - supervisé : fichier NON SUIVI dans le clone, au nom que l'outil lit
 *    (`.claude/rules/striart.md`, `AGENTS.md`, `GEMINI.md`…), inscrit dans
 *    `.git/info/exclude` DU CLONE : le statut git reste propre et le fichier
 *    ne peut être commité que par un `git add -f` délibéré (que la garde des
 *    chemins protégés refuse au merge — c'est voulu).
 *
 * Advisory : les consignes informent, les garde-fous (Test Gate, refus des
 * chemins protégés, garde de profondeur MCP) décident. Un échec d'injection
 * est donc journalisé en avertissement, jamais une erreur qui bloquerait la
 * création d'un agent — mais jamais silencieux non plus.
 */

