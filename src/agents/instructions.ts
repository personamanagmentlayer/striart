/** Manifeste des fichiers injectés dans un clone (hors clone) : seule preuve de propriété. */
function manifestPath(root: string, agent: string): string {
  return path.join(striartDir(root), 'instructions', `${agent}.json`);
}

interface InjectionManifest {
  files: Array<{ path: string; sha256: string }>;
}

const sha256 = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex');

async function readManifest(root: string, agent: string): Promise<InjectionManifest> {
  let raw: { files?: unknown } | null = null;
  try {
    raw = JSON.parse(await readFile(manifestPath(root, agent), 'utf8'));
  } catch (error) {
    // Absent : premier passage. Illisible : la propriété des fichiers ne se
    // prouve plus — manifeste vide, donc AUCUN fichier existant n'est
    // écrasé ni supprimé (fail closed), et on le dit.
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      logger.warn(
        { err: error, agent },
        'Consignes : manifeste illisible, aucun fichier existant ne sera remplacé',
      );
    }
  }
  const files = Array.isArray(raw?.files)
    ? raw.files.filter(
        (f: unknown): f is { path: string; sha256: string } =>
          typeof f === 'object' &&
          f !== null &&
          typeof (f as { path?: unknown }).path === 'string' &&
          typeof (f as { sha256?: unknown }).sha256 === 'string',
      )
    : [];
  return { files };
}

/** En-tête des fichiers Markdown injectés : lisible par l'humain qui ouvre le fichier. */
const GENERATED_HEADER =
  '<!-- Generated by Striart for this agent clone: untracked, ignored locally (.git/info/exclude), regenerated on rebase. Never commit it. -->\n\n';

/**
 * Corps d'un fichier d'instructions selon le format que l'outil attend :
 * une règle Cursor (`.mdc`) et une instruction Copilot (`.instructions.md`)
 * portent un en-tête YAML qui doit ouvrir le fichier (sinon la règle n'est
 * pas appliquée à tous les fichiers) ; le reste est du Markdown simple.
 */
export function instructionFileBody(rel: string, text: string): string {
  if (rel.endsWith('.mdc')) {
    return `---\ndescription: Striart session rules\nalwaysApply: true\n---\n\n${GENERATED_HEADER}${text}`;
  }
  if (rel.endsWith('.instructions.md')) {
    return `---\napplyTo: "**"\n---\n\n${GENERATED_HEADER}${text}`;
  }
  return `${GENERATED_HEADER}${text}`;
}

export interface AttendedInjectionResult {
  /** Outil reconnu (preset du catalogue), null si générique. */
  tool: string | null;
  /** Fichiers écrits, relatifs au clone. */
  written: string[];
  /** Avertissements (aussi journalisés) : consignes non remises, fichier existant… */
  warnings: string[];
}

/** Un chemin relatif sûr (pas d'absolu, pas de `..`, séparateurs normalisés). */
function isSafeRelative(p: string): boolean {
  if (typeof p !== 'string' || p.trim().length === 0) return false;
  if (path.isAbsolute(p) || path.win32.isAbsolute(p)) return false;
  return !p.split(/[\\/]/).some((seg) => seg === '..' || seg === '.git');
}

async function isTracked(clonePath: string, rel: string): Promise<boolean> {
  const { cloneGit } = await import('../clone.js');
  const out = await cloneGit(clonePath).raw(['ls-files', '--', rel]);
  return out.trim().length > 0;
}

async function showAtHead(clonePath: string, rel: string): Promise<string | null> {
  const { cloneGit } = await import('../clone.js');
  try {
    return await cloneGit(clonePath).show([`HEAD:${rel}`]);
  } catch {
    // Absent du commit (le fichier n'est pas suivi à HEAD).
    return null;
  }
}

/** Chemins neutralisés par claudeMdExcludes : consignes du worktree PRINCIPAL et des dossiers intermédiaires. */
export function parentInstructionExcludes(root: string, clonePath: string): string[] {
  const excludes: string[] = [];
  const top = path.resolve(root);
  let dir = path.dirname(path.resolve(clonePath));
  // Du parent du clone jusqu'à la racine du dépôt principal incluse — pas
  // au-delà : un CLAUDE.md placé AU-DESSUS du dépôt est un choix de
  // l'utilisateur (consignes personnelles), pas une fuite du principal.
  while (dir.startsWith(top)) {
    const posix = dir.split(path.sep).join('/');
    excludes.push(
      `${posix}/CLAUDE.md`,
      `${posix}/CLAUDE.local.md`,
      `${posix}/.claude/CLAUDE.md`,
      `${posix}/.claude/rules/**`,
    );
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return excludes;
}

/**
 * Dépose (ou régénère) les consignes d'un agent SUPERVISÉ dans son clone,
 * au nom que lit son outil. Appelé à la création, au `--reuse` et après
 * chaque rebase (un AGENTS.md du commit a pu changer). Ne throw jamais :
 * rend ses avertissements et les journalise.
 */
export async function syncAgentInstructionsToClone({
  root,
  agent,
  clonePath,
  mode = 'attended',
  command = null,
  config = null,
}: {
  root: string;
  agent: string;
  clonePath: string;
  mode?: 'attended' | 'autonomous';
  command?: string | null;
  config?: StriartConfig | null;
}): Promise<AttendedInjectionResult> {
  const result: AttendedInjectionResult = { tool: null, written: [], warnings: [] };
  // Mode autonome : les consignes passent par le canal du profil (argv/ACP),
  // un fichier dans le clone les doublerait.
  if (mode === 'autonomous') return result;
  try {
    const cfg = config ?? (await loadConfig(root));
    await injectAttended({ root, agent, clonePath, command, config: cfg, result });
  } catch (error) {
    result.warnings.push(`instructions not injected: ${(error as Error).message}`);
  }
  for (const warning of result.warnings) {
    logger.warn({ agent, tool: result.tool }, `Consignes Striart : ${warning}`);
  }
  return result;
}

async function injectAttended({
  root,
  agent,
  clonePath,
  command,
  config,
  result,
}: {
  root: string;
  agent: string;
  clonePath: string;
  command: string | null;
  config: StriartConfig;
  result: AttendedInjectionResult;
}): Promise<void> {
  if (!(await stat(clonePath).catch(() => null))) return;
  const settings = resolveInstructionsConfig(config);
  const manifest = await readManifest(root, agent);
  const owned = new Map(manifest.files.map((f) => [f.path, f.sha256]));
  const nextManifest: InjectionManifest = { files: [] };

  const finish = async () => {
    // Fichiers injectés précédemment et plus voulus (config changée) : retirés
    // s'ils sont encore NÔTRES (empreinte identique) — jamais un fichier
    // que l'humain ou l'agent aurait modifié depuis.
    for (const [rel, hash] of owned) {
      if (nextManifest.files.some((f) => f.path === rel)) continue;
      const current = await safeReadText(clonePath, rel);
      if (current !== null && sha256(current) === hash) await safeRemove(clonePath, rel);
    }
    await mkdirPrivate(path.dirname(manifestPath(root, agent)));
    await writeJsonAtomic(manifestPath(root, agent), nextManifest);
  };

  if (!settings.enabled) {
    await finish();
    return;
  }

  const effectiveCommand = attendedCommandOf(command, config.agentCommand);
  const preset = findPresetForCommand(effectiveCommand);
  result.tool = preset?.id ?? null;
  const profile: AgentProfile = preset
    ? { ...materializePreset(preset), command: effectiveCommand }
    : { command: effectiveCommand, args: [] };
  const text = await buildAgentInstructions({
    root,
    agent,
    profileKey: preset?.profileKey ?? 'attended',
    profile,
    config,
    mode: 'attended',
  });
  if (text === null) {
    await finish();
    return;
  }

  /** Écrit `content` à `rel` si le chemin est libre ou déjà nôtre. */
  const tryWrite = async (rel: string, content: string): Promise<'written' | 'taken'> => {
    if (await isTracked(clonePath, rel)) return 'taken';
    // Lien, dossier ou dossier intermédiaire en lien : jamais « libre » — ce
    // n'est pas à nous, et on n'écrit pas à travers (src/safe-write.ts).
    if ((await safeEntryKind(clonePath, rel)) === 'other') return 'taken';
    const current = await safeReadText(clonePath, rel);
    if (current !== null && owned.get(rel) !== sha256(current)) return 'taken';
    await ensureCloneExclude(clonePath, `/${rel}`);
    await safeWriteFile(clonePath, rel, content);
    nextManifest.files.push({ path: rel, sha256: sha256(content) });
    result.written.push(rel);
    return 'written';
  };

  const overrideKey = preset?.id ?? path.basename(effectiveCommand.split(/\s+/)[0] ?? '');
  const candidates =
    settings.attendedFiles[overrideKey] ?? preset?.attendedFiles ?? settings.genericFiles;
  let delivered = false;
  for (const candidate of candidates) {
    // Chemins git : séparateur `/` sur toutes les plateformes (manifeste,
    // .git/info/exclude et pathspecs restent identiques d'un OS à l'autre).
    const rel = candidate.replaceAll('\\', '/');
    if (!isSafeRelative(rel)) {
      result.warnings.push(`unsafe instructions path ignored: ${rel}`);
      continue;
    }
    if (path.basename(rel) === 'AGENTS.md') {
      // D11 : AGENTS.md racine suivi par le dépôt → composite AGENTS.override.md
      // (outils qui le lisent), ou canaux non-fichiers + avertissement.
      if (await isTracked(clonePath, rel)) {
        const overrideRel = path.posix.join(path.posix.dirname(rel), 'AGENTS.override.md');
        if (settings.agentsMd === 'override' && preset?.readsAgentsOverride) {
          const committed = (await showAtHead(clonePath, rel)) ?? '';
          const composite = `${GENERATED_HEADER}${committed.trimEnd()}\n\n${text}`;
          if ((await tryWrite(overrideRel, composite)) === 'written') {
            delivered = true;
            break;
          }
          result.warnings.push(`${overrideRel} exists in the repository: composite not written`);
        } else {
          result.warnings.push(
            `${rel} is tracked by the repository and ${preset?.label ?? effectiveCommand} ${
              settings.agentsMd === 'override'
                ? 'does not read AGENTS.override.md'
                : 'is configured with agentsMd: "non-file"'
            }: Striart rules are not delivered through ${rel}`,
          );
        }
        continue;
      }
    }
    if ((await tryWrite(rel, instructionFileBody(rel, text))) === 'written') {
      delivered = true;
      break;
    }
    result.warnings.push(`${rel} already exists in the clone and is not Striart's: left untouched`);
  }
  if (!delivered) {
    result.warnings.push(
      `no instruction file could be written for ${preset?.label ?? effectiveCommand} (candidates: ${candidates.join(', ') || 'none'}); the agent runs without Striart rules — set agentInstructions.attendedFiles to a file this tool reads`,
    );
  }

  // Claude Code concatène les CLAUDE.md des dossiers PARENTS : depuis
  // <repo>/.striart/agents/<x>/ il lirait ceux du worktree principal
  // (modifications non commitées comprises). Neutralisés par une ignore
  // locale au clone (`claudeMdExcludes` dans .claude/settings.local.json).
  if (preset?.claudeMdExcludes && settings.neutralizeParentInstructions) {
    const rel = '.claude/settings.local.json';
    const content = `${JSON.stringify({ claudeMdExcludes: parentInstructionExcludes(root, clonePath) }, null, 2)}\n`;
    if ((await tryWrite(rel, content)) === 'taken') {
      result.warnings.push(
        `${rel} already exists: the main worktree's CLAUDE.md files are not excluded for this agent`,
      );
    }
  }

  await finish();
}
